const generateButton = document.getElementById("generateButton");
const newButton = document.getElementById("newButton");

const result = document.getElementById("result");

const categorySelect = document.getElementById("category");
const difficultySelect = document.getElementById("difficulty");
const timeSelect = document.getElementById("time");
const mediumSelect = document.getElementById("medium");


const resultTitle = document.getElementById("resultTitle");
const resultFocus = document.getElementById("resultFocus");

const step1 = document.getElementById("step1");
const step2 = document.getElementById("step2");
const step3 = document.getElementById("step3");
const step4 = document.getElementById("step4");

const personalize = document.getElementById("personalize");
const bonus = document.getElementById("bonus");

const resultTime = document.getElementById("resultTime");
const resultCategory = document.getElementById("resultCategory");


let lastExercise = null;


function getExercise() {

  const selectedCategory = categorySelect.value;

  let available = exercises.filter((exercise) => {

    if (selectedCategory === "all") {
      return true;
    }

    return exercise.category === selectedCategory;

  });


  if (available.length === 0) {
    available = exercises;
  }


  let chosen;

  do {

    chosen =
      available[Math.floor(Math.random() * available.length)];

  } while (
    available.length > 1 &&
    chosen === lastExercise
  );


  lastExercise = chosen;

  return chosen;
}


function displayExercise() {

  const exercise = getExercise();

  const selectedTime = timeSelect.value;

  const selectedDifficulty =
    difficultySelect.options[
      difficultySelect.selectedIndex
    ].text;


  resultTitle.textContent = exercise.title;

  resultFocus.textContent =
    `Skill focus: ${exercise.focus}`;


  step1.textContent = exercise.step1;
  step2.textContent = exercise.step2;
  step3.textContent = exercise.step3;
  step4.textContent = exercise.step4;

  personalize.textContent = exercise.personalize;

  bonus.textContent = exercise.bonus;


  resultTime.textContent =
    `${selectedTime} MIN`;

  resultCategory.textContent =
    selectedDifficulty.toUpperCase();


  result.classList.remove("hidden");


  result.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });

}


generateButton.addEventListener(
  "click",
  displayExercise
);


newButton.addEventListener(
  "click",
  displayExercise
);
